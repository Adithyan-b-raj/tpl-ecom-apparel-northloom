import { writeFileSync } from 'node:fs';
import { seedStatements } from '../functions/_lib/seed.js';

const lit = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const NOW = '2026-11-01T00:00:00.000Z';
const lines = seedStatements(NOW).map(({ sql, params }) => {
  let i = 0;
  return sql.replace(/\?/g, () => lit(params[i++])) + ';';
});
writeFileSync(new URL('../seed.sql', import.meta.url), '-- Generated by scripts/gen-seed.mjs from functions/_lib/seed-data.js\n' + lines.join('\n') + '\n');
console.log('seed.sql written,', lines.length, 'statements');
